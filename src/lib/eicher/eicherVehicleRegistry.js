function listEicherVehicleRegistry() {
  return EICHER_VINS.map((vin, index) => ({
    vin,
    source: EICHER_SOURCE,
    apiEnabled: index < MAPPED_VEHICLE_COUNT,
    apiAccessStatus: index < MAPPED_VEHICLE_COUNT ? "API_ENABLED" : "API_ACCESS_PENDING",
  }));
}

function eicherRegistrySummary() {
  const vehicles = listEicherVehicleRegistry();
  return {
    total: vehicles.length,
    mapped: vehicles.filter((vehicle) => vehicle.apiEnabled).length,
    unmapped: vehicles.filter((vehicle) => !vehicle.apiEnabled).length,
    unmappedVins: vehicles.filter((vehicle) => !vehicle.apiEnabled).map((vehicle) => vehicle.vin),
  };
}

